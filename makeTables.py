def collect_verification() -> list:
    from pyblockencode.linear_circuits import (
        LinearElasticityCircuit, LinearPoissonCircuit, verify_columns)

    rows = []
    cases = [("elasticity, $\\nu=0$", lambda: LinearElasticityCircuit(m=2, nu=0.0)),
             ("elasticity, $\\nu=0.3$", lambda: LinearElasticityCircuit(m=2, nu=0.3)),
             ("elasticity, $\\nu=0.45$", lambda: LinearElasticityCircuit(m=2, nu=0.45)),
             ("Poisson 1D, FDM", lambda: LinearPoissonCircuit(m=4, dim=1, disc='fdm')),
             ("Poisson 1D, FEM", lambda: LinearPoissonCircuit(m=4, dim=1, disc='fem')),
             ("Poisson 2D, FDM", lambda: LinearPoissonCircuit(m=3, dim=2, disc='fdm')),
             ("Poisson 2D, FEM", lambda: LinearPoissonCircuit(m=3, dim=2, disc='fem'))]
    for label, mk in cases:
        enc = mk()
        print(f"  verifying {label} ...", end='', flush=True)
        t0 = time.time()
        r = verify_columns(enc)
        rows.append({'label': label, 'm': enc.m, 'qubits': r['num_qubits'],
                     'N0': r['N0'], 'err': r['block_encoding_rel_err']})
        print(f" {r['block_encoding_rel_err']:.1e}  ({time.time()-t0:.1f}s)")
    return rows


def table_verification(rows: list) -> None:
    body_rows = [
        f"{r['label']} & ${r['m']}$ & ${r['N0']}$ & ${r['qubits']}$ & {sci(r['err'])} \\\\"
        for r in rows]
    body = rf"""\begin{{table}}[t]
\centering
\footnotesize
\setlength{{\tabcolsep}}{{5pt}}
\renewcommand{{\arraystretch}}{{1.15}}
\caption{{Block-encoding verification.  Each column of
$\alpha\,U[{{:}}N_0,{{:}}N_0]$ is obtained by a separate statevector simulation
and compared against the classically assembled operator; the table reports the
relative Frobenius error.  Column-wise simulation costs $2^{{n_q}}$ rather than
the $4^{{n_q}}$ of forming the dense unitary, which is what makes the larger
cases reachable.}}
\label{{tab:verification}}
\begin{{tabular}}{{@{{}}lrrrr@{{}}}}
\toprule
Operator & $m$ & $N_0$ & qubits & rel.\ error \\
\midrule
{chr(10).join(body_rows)}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    write("tab_verification.tex", body)


# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--mmax', type=int, default=6,
                    help='largest m in the gate-count table (default 6)')
    ap.add_argument('--nu', type=float, default=0.3)
    ap.add_argument('--no-mcx', action='store_true',
                    help='skip the MCX-ladder comparison column; it is the '
                         'slow one, and it grows fast (46s at m=4)')
    ap.add_argument('--no-verify', action='store_true',
                    help='skip the verification table (statevector sims)')
    args = ap.parse_args()

    try:
        import pyblockencode  # noqa: F401
    except ImportError:
        sys.exit("Run this from the repository root (the folder holding "
                 "pyblockencode/).")

    mcx = not args.no_mcx

    print("LCU terms ...")
    table_lcu(args.nu)

    print("boundary treatments ...")
    table_boundary(args.nu)

    print("gate counts ...")
    gc = collect_gatecounts(args.mmax, mcx)
    table_gatecounts(gc, mcx)

    print("resources ...")
    table_resources(gc)

    if not args.no_verify:
        print("verification ...")
        table_verification(collect_verification())

    print(f"\nDone.  \\input{{tables/...}} from the manuscript.")


if __name__ == '__main__':
    main()