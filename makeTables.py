def collect_gatecounts(mmax: int, mcx: bool) -> dict:
    from qiskit import transpile
    from pyblockencode.linear_circuits import LinearElasticityCircuit
    from pyblockencode.qiskit_encoding import ElasticityCircuit

    gc: dict = {}
    for m in range(2, mmax + 1):
        rec: dict = {}
        print(f"  transpiling m={m} ...", end='', flush=True)
        t0 = time.time()

        n = LinearElasticityCircuit(m=m, nu=0.3)
        tq = transpile(n.circuit(), basis_gates=BASIS, optimization_level=1)
        ops = tq.count_ops()
        rec['new_t'] = ops.get('t', 0) + ops.get('tdg', 0)
        rec['new_cx'] = ops.get('cx', 0)
        rec['new_depth'] = tq.depth()
        rec['new_qubits'] = n.num_qubits

        if mcx:
            o = ElasticityCircuit(m=m, nu=0.3)
            tq = transpile(o.circuit(), basis_gates=BASIS, optimization_level=1)
            ops = tq.count_ops()
            rec['old_t'] = ops.get('t', 0) + ops.get('tdg', 0)
            rec['old_cx'] = ops.get('cx', 0)
            rec['old_depth'] = tq.depth()
            rec['old_qubits'] = o.num_qubits

        gc[str(m)] = rec
        print(f" {time.time()-t0:.1f}s")
    return gc


def table_gatecounts(gc: dict, mcx: bool) -> None:
    ms = sorted(int(k) for k in gc)
    rows = []
    for m in ms:
        r = gc[str(m)]
        if mcx and 'old_t' in r:
            ratio = r['old_t'] / max(r['new_t'], 1)
            rows.append(
                f"${m}$ & ${2**m}$ & {thousands(r['old_t'])} & ${r['old_qubits']}$ & "
                f"{thousands(r['new_t'])} & {thousands(r['new_depth'])} & "
                f"${r['new_qubits']}$ & ${ratio:.0f}\\times$ \\\\")
        else:
            rows.append(
                f"${m}$ & ${2**m}$ & --- & --- & {thousands(r['new_t'])} & "
                f"{thousands(r['new_depth'])} & ${r['new_qubits']}$ & --- \\\\")

    body = rf"""\begin{{table*}}[t]
\centering
\footnotesize
\setlength{{\tabcolsep}}{{6pt}}
\renewcommand{{\arraystretch}}{{1.15}}
\caption{{Measured non-Clifford cost of the elasticity block encoding ($\nu=0.3$),
after transpilation to a Clifford$+T$ basis.  ``MCX ladder'' is the incrementer
built from multi-controlled $X$ gates with $0,\dots,m-1$ controls, the
construction used in the reference implementation of Kharazi
et~al.~\cite{{kharazi2025explicit}}; ``linear'' is the prefix-AND incrementer of
Section~\ref{{sec:encoding}}, which uses $m-1$ additional ancillas.  The linear
$T$-count is exactly affine in $m$, so the $\mathcal{{O}}(\log N)$ claim is
measured rather than inherited by citation.}}
\label{{tab:gatecounts}}
\begin{{tabular}}{{@{{}}rr rr rrr r@{{}}}}
\toprule
& & \multicolumn{{2}}{{c}}{{MCX ladder}} & \multicolumn{{3}}{{c}}{{Linear incrementer}} & \\
\cmidrule(lr){{3-4}}\cmidrule(lr){{5-7}}
$m$ & $N$ & $T$ & qubits & $T$ & depth & qubits & speedup \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
\end{{table*}}
"""
    write("tab_gatecounts.tex", body)


