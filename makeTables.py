#!/usr/bin/env python3
"""
makeTables.py - generate the LaTeX tables for the elasticity block-encoding paper.

Place in the repository root (next to pyblockencode/) and run:

    python makeTables.py                 # tables/*.tex, gate counts to m = 6
    python makeTables.py --mmax 8        # push the scaling table further
    python makeTables.py --mcx           # add the MCX-ladder comparison column

The MCX-ladder column is opt-in because it is the expensive half of the run:
its T-count is superlinear in m where the linear incrementer is affine, so it
costs 46s at m = 4 and grows fast.  Pass --mcx when regenerating the table for
the manuscript; without it those columns are dashed out.

Writes into ./tables/ :

    tab_lcu.tex           the 17 periodic LCU terms, from lcu_terms()
    tab_boundary.tex      L, alpha and components under each boundary treatment
    tab_resources.tex     resource summary for the encoding
    tab_gatecounts.tex    measured T / Toffoli / depth vs m, both constructions
    tab_verification.tex  block-encoding errors, Poisson and elasticity

Every number is computed, never transcribed, so the tables cannot drift from
the code.  Each file is a bare \\begin{table}...\\end{table} meant to be
\\input{} from the manuscript; none of them emit \\documentclass or preamble.

Nothing is cached: every run transpiles from scratch.  A cache is the wrong
trade here, because it silently survives a change to the encoders and hands
back gate counts for circuits that no longer exist.  Use --mmax to bound the
cost instead.
"""
from __future__ import annotations

import argparse
import math
import os
import sys
import time

import numpy as np

TABLES = "tables"

# Clifford+T.  rz survives from the constant-size PREP state preparation and
# does not affect the scaling.
BASIS = ['h', 't', 'tdg', 's', 'sdg', 'x', 'z', 'cx', 'rz']


# ---------------------------------------------------------------------------
# LaTeX helpers
# ---------------------------------------------------------------------------

def fnum(x, nd=4):
    """Fixed-point with an explicit sign, for coefficient columns."""
    return f"{x:+.{nd}f}"


def sci(x, nd=1):
    """Scientific notation as LaTeX math, e.g. 3.8\\times10^{-16}."""
    if x == 0:
        return "0"
    e = int(math.floor(math.log10(abs(x))))
    mant = x / 10 ** e
    return rf"${mant:.{nd}f}\times10^{{{e}}}$"


def thousands(n):
    return f"{int(n):,}".replace(",", r"\,")


HEADER = ("%% GENERATED BY makeTables.py -- DO NOT EDIT BY HAND.\n"
          "%% Regenerate with:  python makeTables.py\n")


def write(name: str, body: str) -> None:
    os.makedirs(TABLES, exist_ok=True)
    path = os.path.join(TABLES, name)
    with open(path, 'w') as f:
        f.write(HEADER + body)
    print(f"  wrote {path}")


